"""Redundant Point Deletion and Path Smoothing Strategy.

Direct implementation of Section 3.3 (Steps 1-4, Page 8-9) of:
Cao et al., 'An Adaptive A* Algorithm for Mobile Robots Global Path Planning', Electronics 2026.

Algorithm Mechanics:
- Step 1: Input node sequence generated by search algorithm.
- Step 2: Collinearity check for 3 consecutive nodes (A, B, C). If collinear and line A-C is obstacle-free, delete B.
- Step 3: If not collinear, check if straight connection line A-C traverses an obstacle.
          If clear of obstacles, eliminate intermediate node B (corner-cut smoothing).
          If it traverses an obstacle, retain B and advance to next triplet.
- Step 4: Iterate until all superfluous nodes are eliminated.
"""

from typing import List, Tuple
from src.grid_map import GridMap


def bresenham_line(p1: Tuple[int, int], p2: Tuple[int, int]) -> List[Tuple[int, int]]:
    """
    Generate all grid cells traversed by the line segment between p1 and p2
    using Bresenham's line algorithm.
    """
    x1, y1 = p1
    x2, y2 = p2
    cells = []

    dx = abs(x2 - x1)
    dy = abs(y2 - y1)
    sx = 1 if x1 < x2 else -1
    sy = 1 if y1 < y2 else -1
    err = dx - dy

    cx, cy = x1, y1
    while True:
        cells.append((cx, cy))
        if cx == x2 and cy == y2:
            break
        e2 = 2 * err
        if e2 > -dy:
            err -= dy
            cx += sx
        if e2 < dx:
            err += dx
            cy += sy

    return cells


def is_line_free(grid: GridMap, p1: Tuple[int, int], p2: Tuple[int, int]) -> bool:
    """
    Check whether the straight line segment between p1 and p2 is completely obstacle-free.
    Includes conservative checks for diagonal corner-cutting against obstacle corners.
    """
    line_cells = bresenham_line(p1, p2)
    for cx, cy in line_cells:
        if not grid.is_free(cx, cy):
            return False

    # Check for diagonal clipping: if two consecutive points in the line move diagonally,
    # ensure we do not cut through two touching orthogonal obstacles
    for i in range(len(line_cells) - 1):
        c1x, c1y = line_cells[i]
        c2x, c2y = line_cells[i + 1]
        if abs(c2x - c1x) == 1 and abs(c2y - c1y) == 1:
            if grid.is_obstacle(c2x, c1y) and grid.is_obstacle(c1x, c2y):
                return False

    return True


def is_collinear(p1: Tuple[int, int], p2: Tuple[int, int], p3: Tuple[int, int]) -> bool:
    """
    Check if three 2D grid points are collinear using the 2D cross product.
    Area of triangle formed by (p1, p2, p3) is 0 if and only if cross product is 0.
    """
    x1, y1 = p1
    x2, y2 = p2
    x3, y3 = p3
    cross_product = (x2 - x1) * (y3 - y1) - (y2 - y1) * (x3 - x1)
    return cross_product == 0


def delete_redundant_points_single_pass(
    path: List[Tuple[int, int]],
    grid: GridMap
) -> List[Tuple[int, int]]:
    """
    Execute a single pass of the 3-node redundant point deletion strategy.
    
    Evaluates triplets (p[i], p[i+1], p[i+2]). If intermediate node p[i+1] is redundant
    (obstacle-free direct line p[i] -> p[i+2]), p[i+1] is eliminated.
    """
    if len(path) <= 2:
        return list(path)

    smoothed = [path[0]]
    i = 0
    while i < len(path) - 1:
        if i + 2 < len(path):
            p_curr = smoothed[-1]
            p_mid = path[i + 1]
            p_next = path[i + 2]

            # Step 2 & 3: Check if connection line traverses an obstacle
            if is_line_free(grid, p_curr, p_next):
                # intermediate node p_mid is deleted, link directly to p_next
                smoothed.append(p_next)
                i += 2
            else:
                # Obstacle detected, retain intermediate node
                smoothed.append(p_mid)
                i += 1
        else:
            # Reached last pair
            smoothed.append(path[-1])
            break

    return smoothed


def delete_redundant_points(
    path: List[Tuple[int, int]],
    grid: GridMap,
    mode: str = "multi_pass",
    max_passes: int = 5
) -> List[Tuple[int, int]]:
    """
    Apply the 3-node redundant point deletion strategy.

    Parameters:
    - path: Ordered sequence of (x, y) coordinates from path search.
    - grid: GridMap instance for obstacle collision checking.
    - mode: "multi_pass" (default, iterates passes until convergence or max_passes)
            or "single_pass" (executes exactly one sequential triplet pass over initial waypoints).
    - max_passes: Maximum iterations when mode is "multi_pass".

    Notes on Paper Fidelity:
    - Step 4 of Section 3.3 in Cao et al. (2026) states: 'Inspect all the nodes in the path node set
      and eliminate all superfluous nodes...'.
    - 'single_pass' adheres strictly to an initial sequential pass over the A* node set.
    - 'multi_pass' (the project default) allows newly joined shortcut vertices to be evaluated
      iteratively, achieving maximum trajectory smoothing across open areas.
    """
    if len(path) <= 2:
        return list(path)

    if mode == "single_pass":
        return delete_redundant_points_single_pass(path, grid)
    elif mode == "multi_pass":
        current_path = list(path)
        for _ in range(max_passes):
            new_path = delete_redundant_points_single_pass(current_path, grid)
            if len(new_path) == len(current_path):
                break
            current_path = new_path
        return current_path
    else:
        raise ValueError(f"Unknown smoothing mode: '{mode}'. Supported modes are 'single_pass' and 'multi_pass'.")

